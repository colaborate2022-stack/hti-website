/* ============================================================================
   build-blog-index.js  —  bake the blog listing into blog.html
   ----------------------------------------------------------------------------
   WHY THIS EXISTS

   blog.html used to paint an empty grid, then fetch every article from Supabase
   and inject the cards. That cost us two things Google measures:

     * Largest Contentful Paint of 8.6s on a throttled mobile connection. The
       cover image cannot even be DISCOVERED until the database round trip has
       finished, so the browser sits idle for seconds with nothing to fetch.
     * No crawlable links. A crawler that does not execute JavaScript saw an
       empty page - no article links at all.

   This script writes the cards straight into blog.html as ordinary HTML, so the
   first paint already contains the real headlines, the real links and a cover
   image the browser can start downloading immediately. The page still refreshes
   itself from Supabase on load, so a newly published article shows up even
   before anyone re-runs this - the baked markup is a fast, crawlable floor, not
   a cache that can go stale on the reader.

   HOW TO RUN

     node tools/build-blog-index.js

   Run it after publishing or unpublishing an article, then commit blog.html.
   There is no install step and no dependency - it uses fetch and fs only.

   It rewrites only the block between the BLOG-INDEX markers in blog.html and
   leaves the rest of the file, including its CRLF line endings, untouched.
   ========================================================================== */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const BLOG_HTML = path.join(ROOT, 'blog.html');
const ROUTES_JS = path.join(ROOT, 'assets', 'blog-routes.js');

const SUPABASE_URL = 'https://ytthcgdsbfagvwcopoaj.supabase.co';
const SUPABASE_ANON_KEY =
  'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6Inl0dGhjZ2RzYmZhZ3Z3Y29wb2FqIiwicm9sZSI6ImFub24iLCJpYXQiOjE3ODMzMjk5MTMsImV4cCI6MjA5ODkwNTkxM30.JIDahcRTu3VbFpZ55Ti5hHg_JrHobk0zh8PSaj9lWLc';

const START = '<!-- BLOG-INDEX:START (generated by tools/build-blog-index.js - do not hand-edit) -->';
const END = '<!-- BLOG-INDEX:END -->';

/* The head carries a preload for the first card's cover - the largest paint on
   the page. It is generated from the same list as the cards so the two can
   never name different files. */
const PRELOAD_START = '<!-- LCP-PRELOAD:START (generated by tools/build-blog-index.js - do not hand-edit) -->';
const PRELOAD_END = '<!-- LCP-PRELOAD:END -->';

/* Only the first card's cover loads eagerly, and it is the only one that asks
   for priority. It is also the one preloaded from the head, because it is the
   largest paint on the page at every width.

   The first three used to be eager and fetchpriority="high" together, on the
   reasoning that they are the top row of a desktop grid. It backfired: three
   high-priority images share the connection three ways, so the one the reader
   is actually waiting for arrived a second later than it needed to, and on a
   phone - one column - cards two and three were below the fold anyway.

   Everything after the first is lazy, which is not the same as slow. Lazy only
   defers images that are outside the viewport, so on a 1440px desktop the rest
   of the top row still loads at once; on a phone they wait, correctly. The
   browser knows which of those it is looking at and this script does not. */
const ABOVE_FOLD = 1;

// ---------------------------------------------------------------------------

function escapeHtml(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function stripTags(s) {
  return String(s == null ? '' : s)
    .replace(/<[^>]*>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function excerpt(s, n) {
  const t = stripTags(s);
  return t.length <= n ? t : t.slice(0, n).replace(/\s+\S*$/, '') + '…';
}

function formatDate(iso) {
  if (!iso) return '';
  const d = new Date(iso);
  if (isNaN(d)) return '';
  const p = (v) => String(v).padStart(2, '0');
  return `${p(d.getDate())}-${p(d.getMonth() + 1)}-${d.getFullYear()}`;
}

function readTime(body) {
  const words = stripTags(body).split(/\s+/).filter(Boolean).length;
  return String(Math.max(1, Math.round(words / 200))).padStart(2, '0') + ' min read';
}

/* Runs assets/blog-routes.js and hands back what it exports, so the browser and
   this script can never disagree about where an article lives or which file its
   cover is. It is a plain IIFE over a `root` object with no DOM in it, so a bare
   object stands in for `window` perfectly well. */
function loadRoutes() {
  const src = fs.readFileSync(ROUTES_JS, 'utf8');
  const root = {};
  new Function('window', src)(root);
  if (!root.HTIBlogRoutes) {
    throw new Error('assets/blog-routes.js did not define HTIBlogRoutes');
  }
  return root.HTIBlogRoutes;
}

/* Same precedence as resolveHref() in blog.html. Keep the two in step. */
function resolveHref(b, routes) {
  if (b.redirect_url) return b.redirect_url;
  const twin = routes.staticPageFor(b.id);
  if (twin) return twin;
  if (b.layout === 'magazine') return `magazine-blog.html?id=${encodeURIComponent(b.id)}`;
  if (b.layout === 'immersive') return `immersive-blog.html?id=${encodeURIComponent(b.id)}`;
  return `blog-post.html?id=${encodeURIComponent(b.id)}`;
}

function renderCard(b, href, idx, routes) {
  /* coverFor() does two things, both explained at length in blog-routes.js: it
     drops our own domain off the URL so the file is fetched same-origin, and it
     swaps the oversized originals the `blogs` table still names for their
     card-sized sibling. */
  const imgSrc = routes.coverFor(b.thumbnail_url || b.cover_image || '');
  const loadHint = idx < ABOVE_FOLD
    ? 'loading="eager" fetchpriority="high"'
    : 'loading="lazy"';

  const cover = imgSrc
    ? `<img class="blog-cover" src="${escapeHtml(imgSrc)}" alt="${escapeHtml(b.title || '')}" ${loadHint} decoding="async" width="1200" height="577" onerror="this.className='blog-cover-ph';this.removeAttribute('src');this.alt='';">`
    : '<div class="blog-cover-ph"></div>';

  const cat = b.category ? `<div class="blog-cat">${escapeHtml(b.category)}</div>` : '';

  let excerptText = '';
  if (b.intro) excerptText = excerpt(b.intro, 160);
  else if (b.body) excerptText = excerpt(b.body, 150);

  const dateStr = b.date ? escapeHtml(b.date) : formatDate(b.created_at);
  const rt = b.reading_time ? escapeHtml(b.reading_time) : readTime(b.intro || b.body);

  return [
    `      <a class="blog-card" href="${escapeHtml(href)}">`,
    `        ${cover}`,
    '        <div class="blog-card-body">',
    cat ? `          ${cat}` : null,
    `          <h3 class="blog-card-title">${escapeHtml(b.title || 'Untitled')}</h3>`,
    `          <p class="blog-excerpt">${escapeHtml(excerptText)}</p>`,
    `          <div class="blog-author">${escapeHtml(b.author || 'Team HTI')}</div>`,
    `          <div class="blog-meta">${dateStr}<span class="dot">&bull;</span>${rt}</div>`,
    '        </div>',
    '      </a>'
  ].filter(Boolean).join('\r\n');
}

// ---------------------------------------------------------------------------

async function main() {
  const routes = loadRoutes();

  const res = await fetch(
    `${SUPABASE_URL}/rest/v1/blogs?is_published=eq.true&order=created_at.desc` +
    '&select=id,title,author,date,reading_time,category,thumbnail_url,intro,created_at,layout,redirect_url,cover_image,body',
    { headers: { apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${SUPABASE_ANON_KEY}` } }
  );
  if (!res.ok) throw new Error(`Supabase request failed: ${res.status}`);

  const blogs = await res.json();
  if (!Array.isArray(blogs) || !blogs.length) throw new Error('No published articles returned');

  /* Two rows can resolve to the same article; newest wins. */
  const seen = new Set();
  const deduped = blogs.filter((b) => {
    const dest = resolveHref(b, routes);
    if (seen.has(dest)) return false;
    seen.add(dest);
    return true;
  });

  const cards = deduped.map((b, i) => renderCard(b, resolveHref(b, routes), i, routes)).join('\r\n');

  let html = fs.readFileSync(BLOG_HTML, 'utf8');
  const s = html.indexOf(START);
  const e = html.indexOf(END);
  if (s === -1 || e === -1) {
    throw new Error('BLOG-INDEX markers not found in blog.html');
  }

  html = html.slice(0, s + START.length) + '\r\n' + cards + '\r\n    ' + html.slice(e);

  /* Preload the first card's cover. Nothing is written if that article has no
     image, rather than a preload for a file that will never be requested -
     Chrome logs a console warning for an unused preload and it would be one
     more thing competing for the connection. */
  const ps = html.indexOf(PRELOAD_START);
  const pe = html.indexOf(PRELOAD_END);
  if (ps === -1 || pe === -1) {
    throw new Error('LCP-PRELOAD markers not found in blog.html');
  }
  const firstCover = routes.coverFor(deduped[0].thumbnail_url || deduped[0].cover_image || '');
  const preload = firstCover
    ? `\r\n  <link rel="preload" as="image" fetchpriority="high" href="${escapeHtml(firstCover)}" />\r\n  `
    : '\r\n  ';
  html = html.slice(0, ps + PRELOAD_START.length) + preload + html.slice(pe);

  fs.writeFileSync(BLOG_HTML, html);

  const dropped = blogs.length - deduped.length;
  console.log(`Wrote ${deduped.length} cards into blog.html` +
    (dropped ? ` (${dropped} duplicate destination${dropped > 1 ? 's' : ''} skipped)` : ''));
  console.log(firstCover ? `Preloading ${firstCover}` : 'First article has no cover; no preload written');
  console.log('Remember to commit blog.html.');
}

main().catch((err) => {
  console.error('build-blog-index failed:', err.message);
  process.exit(1);
});
